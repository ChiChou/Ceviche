    /// The curve at a linear input, interpolated between samples.
    static func value(_ x: Float) -> Float {
        let p = min(1, max(0, x)) * 256
        let i = min(255, Int(p)), t = p - Float(i)
        return samples[i] * (1 - t) + samples[i + 1] * t
    }
    /// The linear input the curve maps to `y`; the curve is monotone, so a binary search finds it.
    static func inverse(_ y: Float) -> Float {
        let y = min(1, max(0, y))
        var lo = 0, hi = 256
        while hi - lo > 1 { let mid = (lo + hi) / 2; if samples[mid] <= y { lo = mid } else { hi = mid } }
        let span = samples[hi] - samples[lo]
        return (Float(lo) + (span > 0 ? (y - samples[lo]) / span : 0)) / 256
    }
