#!/usr/bin/env python3
"""The open-source credits: one manifest, its notices, and the CREDITS.md made from it.

    python3 -I app/scripts/credits.py           check the manifest and that CREDITS.md is current (the build runs this)
    python3 -I app/scripts/credits.py --write   rewrite CREDITS.md from the manifest

Sources/CevicheMac/Resources/OpenSourceLicenses/credits.json is the only file to edit. It ships in the app bundle with
the notice files under credits/<id>/, and Help > Open Source Licenses reads both. To add a dependency, copy its
licence (and NOTICE, and a note of changes where its licence asks for one) into credits/<id>/, add a component
naming those files, and run --write. The check fails on a notice that is missing or empty, a file under credits/
that no component names, a duplicate id, a non-https link or an unknown distribution.
"""
import json
import sys
from pathlib import Path

APP = Path(__file__).resolve().parent.parent
ROOT = APP / "Sources/CevicheMac/Resources/OpenSourceLicenses"
MANIFEST = ROOT / "credits.json"
OUTPUT = APP / "licenses/CREDITS.md"
# Distributions in the order CREDITS.md lists them; the window shows application through optional-model.
SECTIONS = {
    "application": "Application",
    "bundled": "Bundled code and data",
    "build-wrapper": "Codec package wrappers",
    "system": "System libraries",
    "optional-model": "Optional models",
    "build-tool": "Conversion tools — not displayed",
    "proposed": "Proposed assets — not displayed",
}


def check(manifest):
    errors = []
    components = manifest["components"]
    ids = [c["id"] for c in components]
    errors += [f"duplicate id {i}" for i in sorted({i for i in ids if ids.count(i) > 1})]
    named = set()
    for c in components:
        for key in ("id", "name", "license", "projectURL", "distribution", "notices"):
            if not c.get(key):
                errors.append(f"{c.get('id', '?')}: no {key}")
        if not str(c.get("projectURL", "")).startswith("https://"):
            errors.append(f"{c['id']}: projectURL must be https")
        if c.get("distribution") not in SECTIONS:
            errors.append(f"{c['id']}: unknown distribution {c.get('distribution')}")
        for notice in c.get("notices", []):
            path = (ROOT / notice["path"]).resolve()
            named.add(path)
            if ROOT.resolve() not in path.parents:
                errors.append(f"{c['id']}: {notice['path']} is outside OpenSourceLicenses")
            elif not path.is_file() or path.stat().st_size == 0:
                errors.append(f"{c['id']}: {notice['path']} is missing or empty")
    for path in sorted((ROOT / "credits").rglob("*")):
        if path.is_file() and path.name != ".DS_Store" and path.resolve() not in named:
            errors.append(f"{path.relative_to(ROOT)} is not named by any component")
    return errors


def markdown(manifest):
    components = manifest["components"]
    count = sum(len(c["notices"]) for c in components)
    lines = [
        "# Open-source credits",
        "",
        "<!-- Generated by app/scripts/credits.py from Sources/CevicheMac/Resources/OpenSourceLicenses/credits.json; edit that. -->",
        "",
        "**Help → Open Source Licenses…** opens the searchable credits window. Each project links to its website;",
        "licence disclosures show the full offline text, copyright notices, patent grants and attributions.",
        "Optional models appear in a separate section. Build-only tools and proposed assets stay in the inventory",
        "but are left out of the window.",
        "",
        "The [manifest](../Sources/CevicheMac/Resources/OpenSourceLicenses/credits.json) and its notices ship in the app as",
        "they are, in `Ceviche_CevicheMac.bundle`, and the window reads them there. It is the one file to edit:",
        "`scripts/credits.py --write` makes this page from it, and the build checks both.",
        "",
        f"The manifest has {len(components)} records and {count} notice files, collected on {manifest['collectedOn']}.",
        f"Scope: {manifest['scope']}",
    ]
    for distribution, heading in SECTIONS.items():
        rows = [c for c in components if c["distribution"] == distribution]
        if not rows:
            continue
        lines += ["", f"## {heading}", "", "| Project | Licence | Local notices |", "| --- | --- | --- |"]
        for c in rows:
            notices = ", ".join(f"[{Path(n['path']).name}](../Sources/CevicheMac/Resources/OpenSourceLicenses/{n['path']})" for n in c["notices"])
            lines.append(f"| [{c['name']}]({c['projectURL']}) | {c['license']} | {notices} |")
    if manifest.get("notes"):
        lines += ["", "## Provenance notes", ""] + [f"- {note}" for note in manifest["notes"]]
    return "\n".join(lines) + "\n"


def main(arguments):
    manifest = json.loads(MANIFEST.read_text())
    errors = check(manifest)
    if errors:
        sys.exit("credits.json:\n  " + "\n  ".join(errors))
    text = markdown(manifest)
    if arguments == ["--write"]:
        OUTPUT.write_text(text)
    elif arguments:
        sys.exit(__doc__)
    elif not OUTPUT.exists() or OUTPUT.read_text() != text:
        sys.exit("licenses/CREDITS.md is out of date: run python3 -I app/scripts/credits.py --write")


if __name__ == "__main__":
    main(sys.argv[1:])
